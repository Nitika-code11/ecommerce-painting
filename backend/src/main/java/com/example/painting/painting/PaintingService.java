package com.example.painting.painting;

import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * The use cases for paintings. Every public method runs in a database transaction (class-level
 * {@code @Transactional}), so a failure halfway through rolls everything back. Read-only methods say so,
 * which lets the database and Hibernate skip work that is only needed for writes.
 *
 * This layer knows nothing about HTTP: it throws domain exceptions and the web layer maps them to statuses.
 */
@Service
@Transactional
public class PaintingService {
    private final PaintingRepository repository;

    /** Constructor injection: Spring supplies the repository, and tests can pass a mock. */
    public PaintingService(PaintingRepository repository) {
        this.repository = repository;
    }

    /** Builds a new entity from the request and saves it. The id is generated by the database. */
    public Painting create(PaintingRequest request) {
        return repository.save(new Painting(
                request.title(), request.artist(), request.description(),
                request.price(), request.stock(), request.imageUrl()));
    }

    /** One page of paintings; a non-blank {@code title} narrows it to titles containing that text. */
    @Transactional(readOnly = true)
    public Page<Painting> findAll(String title, Pageable pageable) {
        if (title != null && !title.isBlank()) {
            return repository.findByTitleContainingIgnoreCase(title.trim(), pageable);
        }
        return repository.findAll(pageable);
    }

    /** Returns the painting or throws {@link PaintingNotFoundException}. */
    @Transactional(readOnly = true)
    public Painting findById(Long id) {
        return repository.findById(id).orElseThrow(() -> new PaintingNotFoundException(id));
    }

    /**
     * Replaces all editable fields. No explicit save() is needed: the entity is managed inside this
     * transaction, so Hibernate notices the change and writes it when the transaction commits.
     */
    public Painting update(Long id, PaintingRequest request) {
        Painting existing = findById(id);
        existing.apply(request.title(), request.artist(), request.description(),
                request.price(), request.stock(), request.imageUrl());
        return existing;
    }

    /** Deletes the painting, or throws {@link PaintingNotFoundException} if there is none. */
    public void delete(Long id) {
        repository.delete(findById(id));
    }
}
