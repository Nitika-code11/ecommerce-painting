-- Accounts for the API. Passwords are stored only as BCrypt hashes, never as plain text.
-- The table is called "users" because "user" is a reserved word in SQL.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,   -- stored lower-case by the application
    password_hash VARCHAR(100) NOT NULL,   -- a BCrypt hash is 60 characters
    role          VARCHAR(20)  NOT NULL,
    -- Two accounts cannot share a username; this also protects against two sign-ups racing each other.
    CONSTRAINT uq_users_username UNIQUE (username),
    -- Only the roles the application knows about can be stored.
    CONSTRAINT chk_users_role CHECK (role IN ('CUSTOMER', 'ADMIN'))
);
